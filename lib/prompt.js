/**
 * بناء الـ prompt اللي ينرسل للنموذج: يتضمن الأعمدة + البيانات + طلب المستخدم،
 * ويطلب الرد بصيغة JSON فقط بأحد الشكلين المتفق عليهما مع الموقع.
 */

export const RESPONSE_CONTRACT = `صيغة الرد المسموحة (واحدة فقط، بدون أي إضافة):

1) جدول (للفلترة، الترتيب، التجميع، أو أي طلب يرجّع صفوف):
{"type":"table","columns":["اسم العمود", "..."],"rows":[["قيمة","قيمة"],["قيمة","قيمة"]]}

2) نص (للأعداد، الملخصات، الشرح، أو أي جواب جملة):
{"type":"text","answer":"الجواب هنا بالعربي"}`;

export const REPAIR_INSTRUCTION = `ردك السابق ما كان JSON صالح. أعد نفس الجواب الآن بصيغة JSON فقط:
- بدون أي شرح قبل أو بعد.
- بدون أسوار markdown (لا تكتب \`\`\`).
- بدون تعليقات ولا فواصل زائدة.
- ابدأ الرد بحرف { وانتهِ بحرف } فقط.`;

const MAX_ROWS_IN_ANSWER = Number(process.env.MAX_RESULT_ROWS) > 0 ? Number(process.env.MAX_RESULT_ROWS) : 200;

export function buildPrompt({ columns, rows, totalRows, truncated, query }) {
  const columnsBlock = columns
    .map((c, i) => `${i + 1}. ${c && String(c).trim() ? c : '(عمود بدون اسم)'}`)
    .join('\n');

  const dataBlock = JSON.stringify(rows);

  const coverage = truncated
    ? `- هذي عيّنة فقط: أول ${rows.length} صف من إجمالي ${totalRows} صف (البيانات مقتطعة، مو كاملة).`
    : `- هذي كل الصفوف: ${rows.length} صف من إجمالي ${totalRows}.`;

  const system = `أنت "مُرتّب"، محلّل بيانات عربي دقيق تشتغل على جداول إكسل نظّفها المستخدم للتو.

قواعد إلزامية:
1) نفّذ طلب المستخدم على البيانات المعطاة فقط. لا تخترع صفوفًا ولا قيمًا غير موجودة.
2) انسخ القيم كما هي حرفيًا (نفس الكتابة، نفس الأرقام، نفس التواريخ) بدون تعديل أو ترجمة.
3) أرقام: قارن وجمّع كأرقام حتى لو كانت داخل نص، وتجاهل الفواصل وآلاف الفواصل عند الحساب.
4) إذا كان الطلب غير ممكن بالأعمدة الموجودة، أو كان غامضًا، رجّع {"type":"text","answer":"..."} واشرح السبب باختصار واقترح صياغة أفضل.
5) إذا ما فيه نتائج مطابقة، رجّع {"type":"table","columns":[...],"rows":[]}.
6) اكتب الجواب بالعربية بنفس لغة طلب المستخدم.
7) لا تتجاوز ${MAX_ROWS_IN_ANSWER} صف في ردود الجداول، وإذا كانت النتائج أكثر اذكر ذلك داخل الجواب (لو كان نص) أو اقتصر على الأهم.
8) إذا كانت البيانات مقتطعة (مو كل الصفوف) وكان الطلب يحتاج كل البيانات (عدّ/مجموع كامل)، اذكر ذلك بصراحة ولا تعطي رقمًا نهائيًا مضلّلًا.
9) أي سؤال جوابه رقم أو جملة (عدّ، مجموع، متوسط، أعلى/أقل، مقارنة) لازم يكون {"type":"text","answer":"..."} — لا ترجّعه جدولًا.
10) تحقّق من أي حساب قبل ما ترجّع الجواب: أعد الجمع أو العدّ خطوة خطوة مرة ثانية. خطأ رقم واحد يفسد الجواب كله.
11) إذا كان السؤال يحتمل أكثر من معنى (مثل «الصفوف الفريدة»: صفوف مختلفة تمامًا، أم صفوف ما تكرّرت؟) فاختر المعنى الأرجح، واذكر الرقم بوضوح، وأضف سطرًا واحدًا توضّح فيه المعنى الذي حسبته.

${RESPONSE_CONTRACT}

ممنوع تمامًا: أي كلام خارج الـ JSON، أي markdown، أي شرح. الرد لازم يكون JSON قابل للتحليل مباشرة.`;

  const user = `## الأعمدة (${columns.length})
${columnsBlock}

## البيانات (JSON، كل صف مصفوفة بنفس ترتيب الأعمدة)
${dataBlock}

## معلومات إضافية
${coverage}
- إجمالي الصفوف المعلن من الموقع: ${totalRows}
- هل البيانات مقتطعة؟ ${truncated ? 'نعم' : 'لا'}

## طلب المستخدم
${query}

## الآن
نفّذ الطلب وأرجع JSON فقط حسب الصيغة أعلاه.`;

  return { system, user };
}
